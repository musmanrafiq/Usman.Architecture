    f.write('\n')
    f.write('    public async Task<bool> EvaluateAsync(string flagKey, ClaimsPrincipal user, System.Threading.CancellationToken ct = default)\n')
    f.write('    {\n')
    f.write('        // Fail-closed: if flag service is unavailable, assume OFF\n')
    f.write('        try\n')
    f.write('        {\n')
    f.write('            var flag = await _store.GetFlagAsync(flagKey, ct);\n')
    f.write('            if (flag is null || !flag.Enabled)\n')
    f.write('                return false;\n')
    f.write('\n')
    f.write('            // Check if user is in a target tier\n')
    f.write('            if (!string.IsNullOrEmpty(flag.TargetTiers))\n')
