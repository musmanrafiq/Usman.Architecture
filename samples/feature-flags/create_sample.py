    f.write('                var userRoles = user.FindAll(ClaimTypes.Role).Select(r => r.Value).ToList();\n')
    f.write('                var targetRoles = flag.TargetTiers.Split(\',\', StringSplitOptions.RemoveEmptyEntries);\n')
    f.write('                if (userRoles.Any(r => targetRoles.Contains(r.Trim(), StringComparer.OrdinalIgnoreCase)))\n')
