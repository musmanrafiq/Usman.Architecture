    f.write("This sample demonstrates the **single-purpose handler pattern** for saga handlers:\n\n")
    f.write("- **Read handlers**: only SELECT queries, no writes or HTTP calls\n")
    f.write("- **Write handlers**: DB writes + outbox logging, no HTTP calls\n")
    f.write("- **HTTP handlers**: only external calls, no DB writes\n\n")
    f.write("## What this sample shows\n\n")
    f.write("### 1. Bad pattern (do everything in one handler)\n\n")
    f.write("```csharp\n")
    f.write("// BAD: one handler does everything\n")
    f.write("public async Task Handle(OrderPlacedEvent evt)\n")
    f.write("{\n")
    f.write("    var cart = await _db.Carts.FindAsync(evt.CartId);   // READ\n")
    f.write("    var total = CalculateTotal(cart);                    // BIZ LOGIC\n")
    f.write("    await _db.Orders.AddAsync(new Order {...});         // WRITE\n")
    f.write("    await _httpClient.PostAsJsonAsync(\"/payments\", ...); // HTTP\n")
    f.write("}\n")
    f.write("// Problems:\n")
    f.write("// - Connection pool exhausted (DB connection held during HTTP call)\n")
    f.write("// - Long-running transaction (locks held for long time)\n")
    f.write("// - Hard to test (mixes concerns)\n")
    f.write("```\n\n")
    f.write("### 2. Good pattern (split into single-purpose handlers)\n\n")
    f.write("```csharp\n")
    f.write("// 1. Read handler\n")
    f.write("public Task Handle(OrderPlacedEvent evt) {\n")
    f.write("    var product = await _db.Products.FindAsync(evt.ProductId);\n")
    f.write("    // No writes, no HTTP\n")
    f.write("}\n")
    f.write("\n")
    f.write("// 2. Write handler\n")
    f.write("public Task Handle(OrderPlacedEvent evt) {\n")
    f.write("    await _db.Orders.AddAsync(new Order {...});\n")
    f.write("    await _db.SaveChangesAsync(ct);\n")
    f.write("    await _outbox.PublishAsync(new OrderPlacedLoggedEvent {...});\n")
    f.write("}\n")
    f.write("\n")
    f.write("// 3. HTTP handler\n")
    f.write("public Task Handle(OrderPlacedEvent evt) {\n")
    f.write("    var payment = await _httpClient.PostAsJsonAsync(\"/payments\", evt.Amount);\n")
    f.write("    // No DB\n")
    f.write("}\n")
    f.write("```\n")

